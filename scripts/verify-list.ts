/**
 * Builds docs/VERIFICATION.md: every buy link, vendor URL and price that needs a human
 * check, grouped by vendor and by part, with current status and last-verified date.
 * Run with `npm run verify:list` (tsx) after changing parts or vendors.
 *
 * Output is deterministic (no timestamps), so re-running without content changes produces
 * no diff. An entry "needs a check" when its status is unverified, its last_verified is
 * TODO or older than site.staleAfterDays, its URL is TODO, its price is TODO, or it's
 * marked dead or out of stock (checkReasons() in src/lib/staleness.ts).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as prettier from 'prettier';
import { editUrl, site } from '../src/site.config.js';
import { needsCheck } from '../src/lib/staleness.js';
import { ROOT, loadParts, loadVendors } from './lib/content-files.js';

const OUT = join(ROOT, 'docs/VERIFICATION.md');
const staleDays = site.staleAfterDays;
const edit = (path: string) => editUrl(path);

const vendors = loadVendors();
const parts = loadParts();
const vendorById = Object.fromEntries(vendors.map((v) => [v.data.id, v]));

const isTodo = (v: unknown) => v === undefined || v === null || v === 'TODO';
const dateStr = (d: unknown) =>
  isTodo(d) ? 'never' : d instanceof Date ? d.toISOString().slice(0, 10) : String(d);
const priceStr = (p?: { amount: number | string; currency: string }) =>
  !p ? 'none' : isTodo(p.amount) ? `TODO (${p.currency})` : `${p.amount} ${p.currency}`;

// One row per buy option.
const rows = parts.flatMap((p) =>
  (p.data.sources ?? []).map((s, i) => ({ part: p, source: s, index: i })),
);
// Same rule as the site's "needs re-check" badge and Help Wanted (src/lib/staleness.ts).
const pending = rows.filter((r) => needsCheck(r.source));

const vendorPending = vendors.filter((v) => isTodo(v.data.url));

const line = (r: (typeof rows)[number]) => {
  const s = r.source;
  const link = isTodo(s.url) ? '**URL: TODO**' : `<${s.url}>`;
  return [
    `- [ ] **${r.part.data.name}** · ${s.type} · fit ${s.fit}`,
    `  - link: ${link}`,
    `  - status: \`${s.status}\` · verified: ${dateStr(s.last_verified)} · price: ${priceStr(s.price)}`,
    ...(s.notes ? [`  - note: ${s.notes}`] : []),
    `  - edit: [${r.part.file.split('/').pop()}](${edit(r.part.file)}) → \`sources[${r.index}]\``,
  ].join('\n');
};

const out = [];
out.push('# Verification checklist');
out.push(
  '_Generated by `npm run verify:list` from `src/content/parts` and `src/content/vendors`. Don’t edit by hand; edit the YAML and regenerate._',
);
out.push(`## Summary

- Buy links needing a check: **${pending.length}** of ${rows.length}
- Parts with at least one buy link: ${parts.filter((p) => (p.data.sources ?? []).length).length} of ${parts.length}
- Vendors: ${vendors.length} (${vendorPending.length} with no URL yet)

## How to verify one link

1. Open the link on your phone. Confirm it's the right part for the Metacycle and note the price.
2. Tap **edit** to open the YAML file in GitHub's editor, and find the \`sources[n]\` entry.
3. Update:
   - \`status\`: \`live\`, \`out-of-stock\`, or \`dead\` (leave \`unverified\` if you couldn't tell)
   - \`last_verified\`: today's date, e.g. \`2026-11-20\`
   - \`price\`: \`{ amount: 42.5, currency: USD }\` (use the currency shown)
4. Commit to \`main\` (or a branch), then re-run \`npm run verify:list\` to refresh this file.

Entries count as stale ${staleDays} days after \`last_verified\`.`);

// Vendors.
out.push('## Vendors');
for (const v of vendors) {
  const d = v.data;
  const count = rows.filter((r) => r.source.vendor === d.id).length;
  const n = pending.filter((r) => r.source.vendor === d.id).length;
  out.push(
    [
      `- [ ] **${d.name}** (\`${d.id}\`) · ${count} buy link${count === 1 ? '' : 's'}, ${n} to check`,
      `  - URL: ${isTodo(d.url) ? '**TODO**, find the store URL' : `<${d.url}>`}`,
      `  - ships to US: ${d.ships_to_us ?? 'unknown'} · US warehouse: ${d.us_warehouse ?? 'unknown'}`,
      `  - edit: [${v.file.split('/').pop()}](${edit(v.file)})`,
    ].join('\n'),
  );
}

// Buy links by vendor.
out.push('## Buy links by vendor');
for (const v of vendors) {
  const list = pending.filter((r) => r.source.vendor === v.data.id);
  if (!list.length) continue;
  out.push(`### ${v.data.name} (${list.length})`);
  out.push(list.map(line).join('\n'));
}
const orphan = pending.filter((r) => !vendorById[r.source.vendor]);
if (orphan.length) {
  out.push('### Unknown vendor');
  out.push(orphan.map(line).join('\n'));
}

// By part: compact index.
out.push('## By part');
for (const p of parts) {
  const list = rows.filter((r) => r.part === p);
  if (!list.length) {
    out.push(
      `- **${p.data.name}**: no buy links yet ([${p.file.split('/').pop()}](${edit(p.file)}))`,
    );
    continue;
  }
  const items = list
    .map(
      (r) =>
        `  - ${vendorById[r.source.vendor]?.data.name ?? r.source.vendor}: \`${r.source.status}\`, verified ${dateStr(r.source.last_verified)}, price ${priceStr(r.source.price)}`,
    )
    .join('\n');
  out.push(`- **${p.data.name}** ([${p.file.split('/').pop()}](${edit(p.file)}))\n${items}`);
}

const md = await prettier.format(out.join('\n\n') + '\n', {
  ...(await prettier.resolveConfig(OUT)),
  parser: 'markdown',
  filepath: OUT,
});
writeFileSync(OUT, md);
console.log(
  `docs/VERIFICATION.md: ${pending.length} buy links, ${vendorPending.length} vendor URLs need a check.`,
);
